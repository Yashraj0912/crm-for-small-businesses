-- Clientbook CRM schema for PostgreSQL / Neon. Paste into Neon > SQL Editor and run. Safe to re-run.
create extension if not exists pg_trgm;

create table if not exists organizations (
  id integer generated by default as identity primary key,
  name varchar(200) not null,
  created_at timestamptz not null default now()
);

create table if not exists users (
  id integer generated by default as identity primary key,
  org_id integer not null references organizations(id) on delete cascade,
  email varchar(255) not null unique,
  name varchar(200) not null,
  password_hash varchar(255) not null,
  role varchar(20) not null default 'employee' check (role in ('admin','employee')),
  is_active boolean not null default true,
  last_login_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists ix_users_org on users(org_id);

create table if not exists customers (
  id integer generated by default as identity primary key,
  org_id integer not null references organizations(id) on delete cascade,
  name varchar(200) not null,
  email varchar(255), phone varchar(50), company varchar(200), job_title varchar(100),
  category varchar(50),
  tags text[] not null default '{}',
  address text, notes text,
  owner_id integer references users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists ix_customers_org_created on customers(org_id, created_at desc);
create index if not exists ix_customers_org_category on customers(org_id, category);
create index if not exists ix_customers_name_trgm on customers using gin (name gin_trgm_ops);
create index if not exists ix_customers_company_trgm on customers using gin (company gin_trgm_ops);

create table if not exists leads (
  id integer generated by default as identity primary key,
  org_id integer not null references organizations(id) on delete cascade,
  name varchar(200) not null,
  email varchar(255), phone varchar(50), company varchar(200), source varchar(50),
  status varchar(20) not null default 'new' check (status in ('new','contacted','qualified','unqualified','converted')),
  assigned_to integer references users(id) on delete set null,
  follow_up_date date,
  notes text,
  converted_customer_id integer references customers(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists ix_leads_org_status on leads(org_id, status);
create index if not exists ix_leads_org_assigned on leads(org_id, assigned_to);

create table if not exists deals (
  id integer generated by default as identity primary key,
  org_id integer not null references organizations(id) on delete cascade,
  title varchar(200) not null,
  value numeric(12,2) not null default 0 check (value >= 0),
  stage varchar(20) not null default 'new' check (stage in ('new','qualified','proposal','negotiation','won','lost')),
  expected_close date,
  customer_id integer references customers(id) on delete set null,
  owner_id integer references users(id) on delete set null,
  notes text,
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists ix_deals_org_stage on deals(org_id, stage);
create index if not exists ix_deals_org_created on deals(org_id, created_at desc);
create index if not exists ix_deals_customer on deals(customer_id);
create index if not exists ix_deals_won_closed on deals(org_id, closed_at) where stage = 'won';

create table if not exists tasks (
  id integer generated by default as identity primary key,
  org_id integer not null references organizations(id) on delete cascade,
  title varchar(200) not null,
  description text,
  due_date date,
  priority varchar(10) not null default 'medium' check (priority in ('low','medium','high')),
  status varchar(10) not null default 'pending' check (status in ('pending','done')),
  assigned_to integer references users(id) on delete set null,
  customer_id integer references customers(id) on delete set null,
  deal_id integer references deals(id) on delete set null,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists ix_tasks_org_status_due on tasks(org_id, status, due_date);
create index if not exists ix_tasks_org_assigned on tasks(org_id, assigned_to);
create index if not exists ix_tasks_customer on tasks(customer_id);
create index if not exists ix_tasks_deal on tasks(deal_id);

create table if not exists activities (
  id integer generated by default as identity primary key,
  org_id integer not null references organizations(id) on delete cascade,
  type varchar(10) not null check (type in ('call','meeting','email','note')),
  subject varchar(200) not null,
  body text,
  customer_id integer references customers(id) on delete cascade,
  deal_id integer references deals(id) on delete set null,
  user_id integer references users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists ix_activities_org_created on activities(org_id, created_at desc);
create index if not exists ix_activities_customer on activities(customer_id, created_at desc);
create index if not exists ix_activities_deal on activities(deal_id);
create index if not exists ix_activities_user on activities(org_id, user_id, created_at);

create table if not exists ai_usage (
  org_id integer not null references organizations(id) on delete cascade,
  day date not null default current_date,
  calls integer not null default 0,
  primary key (org_id, day)
);

alter table users add column if not exists notify_email boolean not null default true;
